package com.cortez.adoptame.database;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public class TablaUsuario {
    private final static String DDL = "CREATE TABLE usuarios (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR2(100) NOT NULL)";


    private static final String CREAR_SI_NO_EXISTE =
            "BEGIN "
                    + "  EXECUTE IMMEDIATE '" + DDL + "'; "
                    + "EXCEPTION "
                    + "  WHEN OTHERS THEN "
                    + "  IF SQLCODE != -955 THEN RAISE; END IF; "
                    + "END;";
    private TablaUsuario() {
    }
    public static void inicializar() throws SQLException {
        try (
                Connection conn = ConexionDB.obtenerConexion();
                Statement stmt = conn.createStatement()
        ) {
            stmt.execute(CREAR_SI_NO_EXISTE);
            System.out.println("Tabla usuarios creada con éxito");
        }
    }
}
